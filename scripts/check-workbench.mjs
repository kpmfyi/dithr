import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { launch, openConsumer } from './browser-support.mjs';
const out = process.env.WORKBENCH_EVIDENCE_DIR || 'artifacts/workbench-ui';
const url = process.env.SEEDBANK_URL || 'http://127.0.0.1:5187';
await mkdir(out, { recursive: true });
const browser = await launch();
const errors = [];
const checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1, reducedMotion: 'reduce', acceptDownloads: true });
  const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
  await page.goto(url, { waitUntil: 'networkidle' });
  await page.getByLabel('Renderer backend').selectOption('webgl2');
  await page.waitForFunction(() => !document.querySelector('.play-button')?.disabled);
  await page.getByLabel('Search studies').fill('Broken LCD');
  await page.getByRole('button', { name: /Broken LCD/ }).click();
  await page.getByRole('button', { name: 'Inspect recipe ↗' }).click();
  const recipe = async () => JSON.parse(await page.locator('.recipe-code').innerText());
  const blur = () => page.getByLabel('Adjustment step').focus();
  const before = await recipe();
  await page.getByLabel('Scale value', { exact: true }).fill('1.237'); await blur();
  assert.equal((await recipe()).parameters.scale, 1.237);
  await page.getByLabel('Adjustment step').selectOption('0.001');
  await page.getByRole('button', { name: 'Increase Scale', exact: true }).click();
  assert.equal((await recipe()).parameters.scale, 1.238);
  await page.getByRole('button', { name: 'Undo recipe change' }).click();
  assert.equal((await recipe()).parameters.scale, 1.237);
  await page.getByRole('button', { name: 'Redo recipe change' }).click();
  assert.equal((await recipe()).parameters.scale, 1.238);
  await page.getByLabel('Scale value', { exact: true }).fill('999'); await blur();
  assert.equal(await page.getByLabel('Scale value', { exact: true }).inputValue(), '1.238');
  checks.push('numeric precision 0.001, increment controls, invalid draft recovery, undo and redo');
  const preDrag = await recipe();
  await page.getByLabel('Scale', { exact: true }).scrollIntoViewIfNeeded();
  const box = await page.getByLabel('Scale', { exact: true }).boundingBox();
  await page.mouse.move(box.x + box.width * 0.2, box.y + box.height / 2); await page.mouse.down();
  await page.mouse.move(box.x + box.width * 0.48, box.y + box.height / 2, { steps: 8 }); await page.mouse.up();
  assert.notEqual((await recipe()).parameters.scale, preDrag.parameters.scale);
  await page.getByRole('button', { name: 'Undo recipe change' }).click();
  assert.deepEqual(await recipe(), preDrag, 'one undo restores entire slider gesture');
  checks.push('one slider gesture creates one undo entry');
  assert.equal(await page.getByRole('button', { name: 'Lock Motion', exact: true }).getAttribute('aria-pressed'), 'true');
  for (const label of ['Lock Scale', 'Lock seed', 'Lock color 1']) await page.getByRole('button', { name: label, exact: true }).click();
  const locked = await recipe();
  await page.getByRole('button', { name: 'Generate a new variation' }).click();
  const rerolled = await recipe();
  assert.equal(rerolled.seed, locked.seed); assert.equal(rerolled.parameters.scale, locked.parameters.scale);
  assert.equal(rerolled.parameters.speed, locked.parameters.speed); assert.equal(rerolled.palette[0], locked.palette[0]);
  assert.notDeepEqual(rerolled.parameters, locked.parameters);
  await page.getByLabel('Nudge distance').selectOption('0.02');
  await page.getByRole('button', { name: 'Nudge', exact: true }).click();
  const nudged = await recipe();
  assert.equal(nudged.seed, rerolled.seed); assert.deepEqual(nudged.palette, rerolled.palette);
  assert.equal(nudged.parameters.scale, locked.parameters.scale); assert.equal(nudged.parameters.speed, locked.parameters.speed);
  checks.push('full reroll and nudge preserve locked settings, default motion lock, nudge preserves seed/palette');
  await page.getByLabel('Palette preset', { exact: true }).selectOption('cobalt-cream');
  const mapped = await recipe();
  assert.deepEqual(mapped.palette, [locked.palette[0], '#3163ed', '#ffedbb']);
  await page.getByRole('button', { name: 'Swap roles', exact: true }).click();
  assert.deepEqual((await recipe()).palette, [locked.palette[0], '#ffedbb', '#3163ed']);
  await page.getByLabel('Palette hex 1').fill('123456'); await blur();
  assert.equal((await recipe()).palette[0], '#123456', 'manual edits bypass random locks');
  await page.getByLabel('Palette hex 1').fill('invalid'); await blur();
  assert.equal(await page.getByLabel('Palette hex 1').inputValue(), '#123456');
  await page.getByText('Browse 588 palette ideas', { exact: true }).click();
  await page.getByRole('button', { name: 'Use Hot press palette', exact: true }).click();
  assert.deepEqual((await recipe()).palette, ['#123456', '#ff4b2e', '#1b2432']);
  checks.push('preset palettes, palette browser, role swaps and hex entry respect intended lock semantics');
  await page.getByRole('button', { name: 'Lock seed', exact: true }).click();
  const preSeed = await recipe();
  await page.getByRole('button', { name: 'Reroll seed only' }).click();
  const seeded = await recipe();
  assert.notEqual(seeded.seed, preSeed.seed); assert.deepEqual(seeded.palette, preSeed.palette); assert.deepEqual(seeded.parameters, preSeed.parameters);
  for (const label of ['Lock seed', 'Lock Intensity', 'Lock Signal detail', 'Lock color 2', 'Lock color 3']) await page.getByRole('button', { name: label, exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Generate a new variation' }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'Nudge', exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'Swap roles', exact: true }).isDisabled(), true);
  checks.push('seed-only reroll and disabled random actions when all applicable settings are locked');
  await page.getByLabel('Preset name').fill('Precision keeper'); await blur();
  await page.getByLabel('Frozen time in seconds').fill('3.125'); await blur();
  await page.getByRole('button', { name: /Save preset/ }).click();
  const expected = await recipe();
  const event = page.waitForEvent('download'); await page.getByRole('button', { name: 'Recipe ↓', exact: true }).click();
  await (await event).saveAs(`${out}/recipe.json`);
  assert.deepEqual(JSON.parse(await readFile(`${out}/recipe.json`, 'utf8')), expected);
  const pngEvent = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export PNG ↗', exact: true }).click();
  await (await pngEvent).saveAs(`${out}/frozen.png`);
  const size = await page.locator('canvas').evaluate(c => ({ width: c.width, height: c.height }));
  const { page: consumer, errors: consumerErrors } = await openConsumer(browser, url, 'webgl2');
  const independent = await consumer.evaluate(async ({ recipe, width, height }) => {
    const r = window.seedbank.runtime; r.setRecipe(recipe); r.resize(width, height); await r.compile();
    const blob = await r.capture(recipe.time);
    const png = await new Promise(resolve => { const fr = new FileReader(); fr.onload = () => resolve(fr.result); fr.readAsDataURL(blob); });
    return { png, environment: r.environment() };
  }, { recipe: expected, ...size });
  const digest = data => createHash('sha256').update(data).digest('hex');
  assert.equal(digest(Buffer.from(independent.png.split(',')[1], 'base64')), digest(await readFile(`${out}/frozen.png`)));
  assert.deepEqual(consumerErrors, []); await consumer.close();
  checks.push('edited feedback shader exports exact recipe and frozen PNG reproducible in independent consumer');
  // Metadata and precise live edits keep the clock running instead of restarting it.
  await page.getByRole('button', { name: 'Play animation', exact: true }).click();
  await page.waitForFunction(() => parseFloat(document.querySelector('.time-readout').textContent) > 3.5);
  const liveTime = parseFloat(await page.locator('.time-readout').innerText());
  await page.getByLabel('Intensity value', { exact: true }).fill('1.123'); await blur();
  assert.ok(parseFloat(await page.locator('.time-readout').innerText()) >= liveTime);
  await page.getByLabel('Preset name').fill('Live tuning'); await blur();
  assert.ok(parseFloat(await page.locator('.time-readout').innerText()) >= liveTime);
  await page.getByRole('button', { name: 'Pause animation', exact: true }).click();
  checks.push('live parameter and name edits preserve playback time');
  for (const label of ['Lock Scale', 'Lock seed', 'Lock Intensity', 'Lock Signal detail', 'Lock color 1', 'Lock color 2', 'Lock color 3']) await page.getByRole('button', { name: label, exact: true }).click();
  await page.getByRole('button', { name: 'Hide recipe ↗' }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${out}/desktop.png`, fullPage: true });
  await page.evaluate(() => window.scrollTo(0, 700));
  assert.ok((await page.locator('.studio').boundingBox()).y >= 0, 'preview stays visible while tuning lower controls');
  await page.screenshot({ path: `${out}/sticky-preview.png` });
  for (const width of [390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}px viewport does not overflow`);
    await page.screenshot({ path: `${out}/mobile-${width}.png`, fullPage: true });
  }
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('tab', { name: /Saved/ }).click();
  await page.getByRole('button', { name: /Precision keeper seed / }).click();
  await page.getByRole('button', { name: 'Inspect recipe ↗' }).click();
  const reopened = await recipe();
  assert.deepEqual(reopened.parameters, expected.parameters); assert.deepEqual(reopened.palette, expected.palette);
  assert.equal(reopened.time, expected.time); assert.equal(reopened.seed, expected.seed);
  assert.deepEqual(errors, []);
  checks.push('sticky desktop preview; 390px and 320px layouts; saved precision/palette/seed/time survive reload');
  const report = { checkedAt: new Date().toISOString(), browser: await browser.version(), environment: independent.environment, timing: 'Interaction and deterministic frozen-render checks; no performance claim', checks, errors, initialRecipe: before.id };
  await writeFile(`${out}/report.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
